function translateGrade(g) {
  if (!g || g.trim() === '-') return '';
  let t = g.trim();
  GRADE_PHRASES.forEach(([re, ar]) => { t = t.replace(re, ar); });
  t = t.replace(/\s*-\s*/g, ' - ').replace(/\s{2,}/g, ' ').trim();
  // «إسناده صحيح صحيح البخاري» ← «إسناده صحيح، وهو في صحيح البخاري»
  t = t.replace(/\)\s+صحيح مسلم/g, ')، وصحيح مسلم');
  t = t.replace(/(\S)\s+(?:-\s+)?(صحيح البخاري|صحيح مسلم|البخاري ومسلم)/g, '$1، وهو في $2');
  return /[A-Za-z]{3,}/.test(t) ? `${t} (${g.trim()})` : t;
}

