#!/usr/bin/env python3
"""تصنيف إضافي لمواد المكتبة بالكلمات المفتاحية في العنوان والوصف (لأن واجهة IslamHouse لا تتيح التصنيفات الفرعية)."""
import json, re, sys
p = sys.argv[1] if len(sys.argv) > 1 else 'data/lib-index.json'
d = json.load(open(p, encoding='utf-8'))
KW = {
    'akhirah': r'اليوم الآخر|اليوم الاخر|القبر|البرزخ|القيامة|جهنم|الموت|الجنائز|الجنازة|الميت|الحشر|الشفاعة|الصراط(?! المستقيم)|أشراط الساعة|علامات الساعة|الآخرة|الجنة والنار|صفة الجنة|صفة النار',
    'masajid': r'المسجد|المساجد|مسجد|الحرمين|الأقصى|الاعتكاف',
    'ulama': r'سيرة الشيخ|سيرة الإمام|حياة الإمام|حياة الشيخ|سير أعلام|فضل الصحابة|فضائل الصحابة|الصحابي|أمهات المؤمنين|^ترجمة (الشيخ|الإمام|العلامة)',
    'tajweed': r'تجويد|التجويد|القراءات|التلاوة|مخارج الحروف|أحكام النون|الجزرية|تحفة الأطفال|الشاطبية|ترتيل',
    'usul': r'أصول الفقه|الأصول|القواعد الفقهية|القواعد الأصولية|الورقات|مقاصد الشريعة|الاجتهاد',
    'tafsir': r'تفسير|التفسير|علوم القرآن|سورة|آيات|القرآن الكريم',
    'hadith': r'الحديث|الأربعين|صحيح البخاري|صحيح مسلم|السنن|مصطلح|بلوغ المرام|عمدة الأحكام|رياض الصالحين',
    'tarikh': r'تاريخ|التاريخ|السيرة النبوية|الغزوات|غزوة|الخلفاء|الدولة|الفتوحات|الحضارة',
}
TITLE_ONLY = {'akhirah', 'masajid', 'ulama', 'tajweed', 'usul'}
added = {k: 0 for k in KW}
for it in d['items']:
    txt = f"{it['t']} {it.get('d', '')}"
    for sec, rx in KW.items():
        src = it['t'] if sec in TITLE_ONLY else txt
        if sec not in it['s'] and re.search(rx, src):
            it['s'].append(sec); added[sec] += 1
json.dump(d, open(p, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
print('added', added)
